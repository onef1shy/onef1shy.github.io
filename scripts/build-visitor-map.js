import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { geoPath, geoProjection } from 'd3-geo';
import { feature, mesh } from 'topojson-client';

const topology = JSON.parse(await readFile(new URL('./data/countries-110m.json', import.meta.url), 'utf8'));
const land = feature(topology, topology.objects.land);
// Exclude Antarctica and its offshore islands from the artwork itself.
for (const item of land.features) {
  item.geometry.coordinates = item.geometry.coordinates.filter(polygon =>
    polygon.some(ring => ring.some(([, latitude]) => latitude >= -60)));
}
const width = 900;
const height = width / 2.04;
const centralMeridian = 11.5;
const latitudeBounds = [-60, 85];
const padding = 14;
const miller = latitude => 1.25 * Math.log(Math.tan(Math.PI / 4 + 0.4 * latitude));
const north = miller(latitudeBounds[1] * Math.PI / 180);
const south = miller(latitudeBounds[0] * Math.PI / 180);
const scale = (width - 2 * padding) / (2 * Math.PI);
// Fill the existing compact frame with the inhabited continents, without poles.
const verticalScale = (height - 2 * padding) / (scale * (north - south));
const projection = geoProjection((longitude, latitude) => [longitude, miller(latitude) * verticalScale])
  .rotate([-centralMeridian, 0])
  .precision(0.15)
  .scale(scale)
  .translate([width / 2, padding + scale * verticalScale * north]);
const draw = geoPath(projection).digits(2);
const path = draw(land);
const borders = draw(mesh(topology, topology.objects.countries, (a, b) => a !== b));
const metadata = {
  width, height, centralMeridian, verticalScale, latitudeBounds,
  scale: projection.scale(), translate: projection.translate(),
};
await mkdir(new URL('../images/visitor-map/', import.meta.url), { recursive: true });
await mkdir(new URL('../assets/visitor-map/', import.meta.url), { recursive: true });
await writeFile(new URL('../images/visitor-map/world.svg', import.meta.url),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${width}" height="${height}"><path fill="#ffffff" d="${path}"/><path class="country-borders" fill="none" stroke="#c4dce9" stroke-width="1.2" stroke-linejoin="round" stroke-linecap="round" d="${borders}"/></svg>\n`);
await writeFile(new URL('../assets/visitor-map/projection.js', import.meta.url),
  `// Generated by npm run map:build; Natural Earth land, compact Miller projection.\nexport const projection = Object.freeze(${JSON.stringify(metadata)});\n`);
console.log(`Built local world SVG with country borders (${path.length + borders.length} path characters) and matching marker projection.`);
